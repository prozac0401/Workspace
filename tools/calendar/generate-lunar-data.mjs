import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import KoreanLunarCalendar from 'korean-lunar-calendar';

const require = createRequire(import.meta.url);
const packageFile = require.resolve('korean-lunar-calendar/package.json');
const packageInfo = JSON.parse(await readFile(packageFile, 'utf8'));
if (packageInfo.version !== '0.4.0') throw new Error('Expected korean-lunar-calendar 0.4.0. Run npm ci in tools/calendar.');
const license = (await readFile(join(dirname(packageFile), 'LICENSE'), 'utf8')).replaceAll('\r\n', '\n').trim();
const args = process.argv.slice(2);
if (args.some(arg => arg !== '--check') || args.length > 1) throw new Error('Usage: node generate-lunar-data.mjs [--check]');

const DAY_MS = 86_400_000;
const minimum = Date.UTC(1983, 0, 1);
const end = Date.UTC(2051, 0, 1);
const calendar = new KoreanLunarCalendar();
const rows = [];
let precedingMonth = null;
for (let day = Date.UTC(1982, 0, 1); day < end; day += DAY_MS) {
  const solar = new Date(day);
  if (!calendar.setSolarDate(solar.getUTCFullYear(), solar.getUTCMonth() + 1, solar.getUTCDate())) throw new Error('Reference rejected a supported Gregorian date.');
  const lunar = calendar.getLunarCalendar();
  if (lunar.day !== 1) continue;
  const row = [solar.toISOString().slice(0, 10), lunar.year, lunar.month, lunar.intercalation];
  if (day < minimum) precedingMonth = row;
  else rows.push(row);
}
if (!precedingMonth) throw new Error('Missing month containing the first supported date.');
rows.unshift(precedingMonth);
const output = `/*
Generated by tools/calendar/generate-lunar-data.mjs. Do not edit the table.
Source: korean-lunar-calendar 0.4.0 (KASI-based table; not a live KASI response).
https://github.com/usingsky/korean_lunar_calendar_js
Rows: [Gregorian month start, lunar year, lunar month, leap month].

${license}
*/
export const LUNAR_MONTH_STARTS = Object.freeze([\n${rows.map(row => `  Object.freeze(${JSON.stringify(row)}),`).join('\n')}\n]);\n`;
const target = new URL('../../docs/assets/calendar/lunar-data.mjs', import.meta.url);
if (args.includes('--check')) {
  if (await readFile(target, 'utf8') !== output) throw new Error('Lunar table differs from the pinned generator output.');
  console.log(`Lunar table reproducible: ${rows.length} month starts, 1983–2050.`);
} else {
  await writeFile(target, output, 'utf8');
  console.log(`Generated lunar table: ${rows.length} month starts, 1983–2050.`);
}
